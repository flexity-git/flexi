-- stuck-orders: merchant-defined rules and alert bookkeeping.
-- Reads the order mirror owned by the mirror module (shoptet_orders,
-- shoptet_order_statuses, shoptet_sync_state) but never writes to it.
--
-- No rows are inserted here on purpose: status IDs and names differ per store,
-- so every merchant writes their own rules. See README.md for an example.

create table if not exists stuck_order_rules (
  id bigint generated by default as identity primary key,
  -- null = the rule applies to every configured store
  store_key text,
  -- match on status_id, on status_name (case-insensitive), or on either when both are set
  status_id integer,
  status_name text,
  max_business_hours numeric not null check (max_business_hours > 0),
  channel text not null default 'orders' check (channel in ('alerts', 'orders', 'products')),
  enabled boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  constraint stuck_order_rules_status_required check (status_id is not null or status_name is not null)
);

create table if not exists stuck_order_alerts (
  id bigint generated by default as identity primary key,
  store_key text not null,
  order_code text not null,
  rule_id bigint not null references stuck_order_rules (id) on delete cascade,
  first_alerted_at timestamptz not null,
  last_alerted_at timestamptz not null,
  alert_count integer not null default 1,
  -- set when the order no longer matches the rule (left the status)
  resolved_at timestamptz
);

-- At most one open alert per order and rule. A resolved alert stays as history;
-- if the order enters the status again later, a new row starts a new cycle.
create unique index if not exists stuck_order_alerts_open_uq
  on stuck_order_alerts (store_key, order_code, rule_id)
  where resolved_at is null;

create index if not exists stuck_order_alerts_rule_idx on stuck_order_alerts (rule_id);
